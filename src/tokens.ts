/** A deterministic icon token for an id — stable across renders and sessions. */
export function tokenIcon(id: string): ComponentType<LucideProps> {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) | 0;
  return POOL[Math.abs(h) % POOL.length];
}
